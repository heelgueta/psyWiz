#!/usr/bin/env python3
"""Writes the jamovi definition files (jamovi/<analysis>.{a,r,u}.yaml).

    python3 tools/gen_yaml.py        (from the repository root)

Most analyses share blocks of options (how items are treated, estimator,
missing values, decision criteria, figure options) and table layouts. Keeping
many hand-written yaml files in sync is error-prone, so they are generated
from the small helpers below. Edit THIS file, run it, then rebuild the module.

Not generated: multiEstCfa.*.yaml (written by hand), 0000.yaml, 00refs.yaml.

Conventions
  * an option that changes which models are fitted must be in the `refit`
    list of its analysis: the cached results are cleared when one of those
    options changes (see docs/DESIGN.md, "jamovi layer");
  * option names become arguments of the generated R functions, so renaming
    one is a breaking change for R users.
"""
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "jamovi"
STAMP = "# GENERATED by tools/gen_yaml.py -- edit that script, not this file.\n"


# ----------------------------------------------------------------- options --
def q(text):
    return "''" if text == "" else "'" + text.replace("'", "''") + "'"


def desc(text):
    return "    description:\n      R: >\n        " + text + "\n"


def o_bool(name, title, default, text):
    return (f"  - name: {name}\n    title: {q(title)}\n    type: Bool\n"
            f"    default: {'true' if default else 'false'}\n" + desc(text))


def o_num(name, title, default, lo, hi, text, kind="Number"):
    return (f"  - name: {name}\n    title: {q(title)}\n    type: {kind}\n    default: {default}\n"
            f"    min: {lo}\n    max: {hi}\n" + desc(text))


def o_str(name, title, default, text):
    return f"  - name: {name}\n    title: {q(title)}\n    type: String\n    default: {q(default)}\n" + desc(text)


def o_list(name, title, options, default, text):
    out = f"  - name: {name}\n    title: {q(title)}\n    type: List\n    options:\n"
    for key, label in options:
        out += f"      - name: {key}\n        title: {q(label)}\n"
    return out + f"    default: {default}\n" + desc(text)


def o_vars(name, title, text, permitted=("numeric", "factor"), suggested=("ordinal", "continuous"), single=False):
    out = f"  - name: {name}\n    title: {q(title)}\n    type: {'Variable' if single else 'Variables'}\n    suggested:\n"
    out += "".join(f"      - {s}\n" for s in suggested) + "    permitted:\n"
    return out + "".join(f"      - {s}\n" for s in permitted) + desc(text)



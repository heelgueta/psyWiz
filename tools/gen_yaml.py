def ui_check_with(name, boxes, indent=10):
    pad = " " * indent
    out = f"{pad}- type: CheckBox\n{pad}  name: {name}\n{pad}  children:\n"
    for b in boxes:
        out += f"{pad}    - type: TextBox\n{pad}      name: {b}\n{pad}      format: number\n{pad}      enable: ({name})\n"
    return out



def ui_supplier(boxes):
    return "  - type: VariableSupplier\n    persistentItems: false\n    stretchFactor: 1\n    children:\n" + "".join(boxes)


def ui_target(label, name, single=False):
    return (f"      - type: TargetLayoutBox\n        label: {label}\n        children:\n"
            f"          - type: VariablesListBox\n            name: {name}\n" +
            ("            maxItemCount: 1\n" if single else "") + "            isTarget: true\n")



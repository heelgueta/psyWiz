def main():
    for name, a in ANALYSES.items():
        ctx = dict(a, name=name, stamp=STAMP,
                   model_clear="".join(f"      - {k}\n" for k in a["model_keys"]))
        (OUT / f"{name}.a.yaml").write_text(A_YAML.format(**ctx), encoding="utf-8")
        (OUT / f"{name}.r.yaml").write_text(R_YAML.format(**ctx), encoding="utf-8")
        (OUT / f"{name}.u.yaml").write_text(U_YAML.format(**ctx), encoding="utf-8")
        print("wrote", name)


if __name__ == "__main__":
    main()

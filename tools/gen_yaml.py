def ui_box(children, indent=2):
    pad = " " * indent
    return f"{pad}- type: LayoutBox\n{pad}  margin: large\n{pad}  children:\n" + "".join(children)


def ui_ctl(kind, name, indent=6, extra=""):
    pad = " " * indent
    fmt = ""
    if kind == "TextBox":
        fmt = f"{pad}  format: number\n"
    if kind == "TextBoxS":
        kind, fmt = "TextBox", f"{pad}  format: string\n"
    return f"{pad}- type: {kind}\n{pad}  name: {name}\n{fmt}{extra}"


def ui_collapse(label, children, collapsed=True):
    return (f"  - type: CollapseBox\n    label: {label}\n    collapsed: {'true' if collapsed else 'false'}\n"
            "    stretchFactor: 1\n    children:\n" + "".join(children))



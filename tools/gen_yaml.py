#!/usr/bin/env python3
"""Writes the jamovi definition files of the two group-CFA analyses.

    python3 tools/gen_yaml.py        (from the repository root)

groupCfaOne (One-Factor Group CFA) and groupCfaCorr (Correlated-Factors Group
CFA) differ only in how the model is specified: one list of items versus a
list of factor boxes. Everything else (options, result tables, most of the
options panel) is identical, so their .a.yaml / .r.yaml / .u.yaml files are
generated from the templates below instead of being kept in sync by hand.

Edit THIS file, run it, then rebuild the module. multiEstCfa.*.yaml is written
by hand and is not touched by this script.
"""

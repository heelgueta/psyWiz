def head_a(name, title, blurb, usage):
    return (f"---\n{STAMP}# {title} ({name}): OPTIONS. jmvtools compiles this file (with the .r.yaml)\n"
            f"# into R/{name}.h.R.\nname: {name}\ntitle: {title}\nmenuGroup: psyWiz\n"
            "version: '1.0.0'\njas: '1.2'\ndescription:\n  main: >\n    " + blurb +
            "\n  R:\n    dontrun: true\n    usage: |\n" + usage + "options:\n")


def head_r(name, title, refs):
    return (f"---\n{STAMP}# {title} ({name}): RESULTS.\nname: {name}\ntitle: {title}\njrs: '1.1'\nrefs:\n" +
            clear(refs, 2) + "items:\n")


def head_u(name, title):
    return (f"{STAMP}# {title} ({name}): OPTIONS PANEL. compilerMode `tame`: jmvtools keeps this layout and\n"
            f"# only appends controls for options that are missing from it.\ntitle: {title}\nname: {name}\n"
            "jus: '3.0'\nstage: 0\ncompilerMode: tame\nchildren:\n")


def write(name, a, r, u):
    (OUT / f"{name}.a.yaml").write_text(a + "...\n", encoding="utf-8")
    (OUT / f"{name}.r.yaml").write_text(r + "...\n", encoding="utf-8")
    (OUT / f"{name}.u.yaml").write_text(u, encoding="utf-8")
    print("wrote", name)


